// Bundles server/ into dist/server.mjs and writes the licenses of every
// bundled package to dist/THIRD_PARTY_LICENSES.txt.

import { build } from 'esbuild';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const result = await build({
  entryPoints: ['server/server.js'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  outfile: 'dist/server.mjs',
  banner: { js: '// Generated by `npm run build` from server/. Do not edit. Licenses: THIRD_PARTY_LICENSES.txt' },
  metafile: true,
  logLevel: 'warning',
});

const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = /^node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
  if (match && !packages.has(match[1])) packages.set(match[1], join('node_modules', match[1]));
}

const sections = [...packages.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, dir]) => {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const file = readdirSync(dir).find((f) => /^(license|licence|copying)(\..*)?$/i.test(f));
  const text = file ? readFileSync(join(dir, file), 'utf8').trim() : `License: ${pkg.license ?? 'unknown'}`;
  return `${'='.repeat(78)}\n${name}@${pkg.version} (${pkg.license ?? 'unknown'})\n${'='.repeat(78)}\n${text}\n`;
});
writeFileSync(join(dirname('dist/server.mjs'), 'THIRD_PARTY_LICENSES.txt'),
  `Third-party software bundled in dist/server.mjs\n\n${sections.join('\n')}`);
console.log(`dist/server.mjs + licenses for ${packages.size} packages: ${[...packages.keys()].join(', ')}`);
